export type TranslationKey = keyof typeof translations.pl;

type TranslationMap = Record<
  keyof typeof translations.pl | keyof typeof translations.ua | keyof typeof translations.de | keyof typeof translations.en,
  string
> & Record<string, string>;

export const supportedLanguages = ["pl", "en"] as const;

export const normalizeLanguage = (lang: string | null | undefined): SupportedLanguage => {
  const normalized = (lang || "").toLowerCase();
  if (normalized.startsWith("en")) return "en";
  return "pl";
};

export const getTranslations = (lang: string | null | undefined): TranslationMap => ({
  ...translations.pl,
  ...translations[normalizeLanguage(lang)],
} as TranslationMap);

export const detectLanguage = (): SupportedLanguage => {
  const docLang = document.documentElement.lang;
  const navLang = navigator.language;
  return normalizeLanguage(docLang || navLang);
};

